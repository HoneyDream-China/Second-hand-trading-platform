package edu.campus.loop.common;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.List;
import javax.sql.DataSource;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.InitializingBean;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * 应用启动时创建所有业务表。
 * <p>全部语句使用 {@code IF NOT EXISTS}，重复启动不会报错，也不会删除或覆盖已有数据，
 * 因此注册的用户、发布的商品和交易记录会一直保存在数据库文件中。</p>
 */
@Component
public class DatabaseSchemaInitializer implements InitializingBean {
    private static final Logger log = LoggerFactory.getLogger(DatabaseSchemaInitializer.class);

    /**
     * 建表顺序即外键依赖顺序：users → auth_tokens / products → product_images / trades → trade_status_logs。
     * <p>trades 表的 {@code active_product_id} 是计算列：仅当状态为 PENDING 时等于 product_id，
     * 其余状态为 NULL，配合唯一索引实现“同一商品只能有一笔待处理交易”，
     * 等价于 PostgreSQL 的部分唯一索引（H2 不支持带 WHERE 的索引）。</p>
     */
    private static final List<String> SCHEMA = List.of(
            """
            CREATE TABLE IF NOT EXISTS users (
                id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                account       VARCHAR(64)  NOT NULL UNIQUE,
                password_hash VARCHAR(255) NOT NULL,
                nickname      VARCHAR(64)  NOT NULL,
                avatar_url    VARCHAR(512),
                phone         VARCHAR(32),
                status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
                created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'DISABLED'))
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS auth_tokens (
                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id    BIGINT NOT NULL REFERENCES users(id),
                token_hash VARCHAR(128) NOT NULL UNIQUE,
                expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
                revoked_at TIMESTAMP WITH TIME ZONE,
                created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS products (
                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                seller_id   BIGINT NOT NULL REFERENCES users(id),
                title       VARCHAR(120) NOT NULL,
                description TEXT NOT NULL,
                price       NUMERIC(12,2) NOT NULL,
                category    VARCHAR(64) NOT NULL,
                condition   VARCHAR(32) NOT NULL,
                status      VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
                version     BIGINT NOT NULL DEFAULT 0,
                created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT ck_products_price CHECK (price >= 0),
                CONSTRAINT ck_products_version CHECK (version >= 0),
                CONSTRAINT ck_products_status CHECK (status IN ('DRAFT', 'ON_SALE', 'SOLD', 'OFF_SHELF'))
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS product_images (
                id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id BIGINT NOT NULL REFERENCES products(id) ON DELETE CASCADE,
                url        VARCHAR(512) NOT NULL,
                sort_order INTEGER NOT NULL,
                created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT uk_product_images_order UNIQUE (product_id, sort_order),
                CONSTRAINT ck_product_images_order CHECK (sort_order >= 0)
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS trades (
                id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id        BIGINT NOT NULL REFERENCES products(id),
                buyer_id          BIGINT NOT NULL REFERENCES users(id),
                seller_id         BIGINT NOT NULL REFERENCES users(id),
                message           VARCHAR(500),
                status            VARCHAR(16) NOT NULL DEFAULT 'PENDING',
                active_product_id BIGINT GENERATED ALWAYS AS (CASE WHEN status = 'PENDING' THEN product_id ELSE NULL END),
                created_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                updated_at        TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT ck_trades_status CHECK (status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED')),
                CONSTRAINT ck_trades_distinct_participants CHECK (buyer_id <> seller_id)
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS trade_status_logs (
                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                trade_id    BIGINT NOT NULL REFERENCES trades(id) ON DELETE CASCADE,
                from_status VARCHAR(16),
                to_status   VARCHAR(16) NOT NULL,
                operator_id BIGINT NOT NULL REFERENCES users(id),
                created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                CONSTRAINT ck_trade_logs_status CHECK (to_status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED'))
            )
            """,
            "CREATE UNIQUE INDEX IF NOT EXISTS uk_product_active_trade ON trades(active_product_id)",
            "CREATE INDEX IF NOT EXISTS idx_auth_tokens_user_active ON auth_tokens(user_id, expires_at)",
            "CREATE INDEX IF NOT EXISTS idx_products_seller_status ON products(seller_id, status)",
            "CREATE INDEX IF NOT EXISTS idx_products_status_created ON products(status, created_at)",
            "CREATE INDEX IF NOT EXISTS idx_product_images_product ON product_images(product_id, sort_order)",
            "CREATE INDEX IF NOT EXISTS idx_trades_buyer_status ON trades(buyer_id, status, created_at)",
            "CREATE INDEX IF NOT EXISTS idx_trades_seller_status ON trades(seller_id, status, created_at)",
            "CREATE INDEX IF NOT EXISTS idx_trades_product ON trades(product_id, created_at)",
            "CREATE INDEX IF NOT EXISTS idx_trade_logs_trade_created ON trade_status_logs(trade_id, created_at)"
    );

    private final DataSource dataSource;
    private final String url;

    public DatabaseSchemaInitializer(DataSource dataSource, @Value("${spring.datasource.url}") String url) {
        this.dataSource = dataSource;
        this.url = url;
    }

    @Override
    public void afterPropertiesSet() throws SQLException {
        if (!url.startsWith("jdbc:h2:")) {
            // 其他数据库请执行对应的建表脚本，避免方言不兼容导致启动失败。
            log.info("检测到非 H2 数据源，跳过自动建表：{}", url);
            return;
        }
        try (Connection connection = dataSource.getConnection(); Statement statement = connection.createStatement()) {
            for (String ddl : SCHEMA) {
                statement.execute(ddl);
            }
        }
        log.info("数据库表结构已就绪（已有数据保持不变）");
    }
}
