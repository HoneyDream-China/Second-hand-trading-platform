package edu.campus.loop.trade;

import edu.campus.loop.common.BusinessException;
import edu.campus.loop.product.ProductDtos.TradableProduct;
import edu.campus.loop.product.ProductFacade;
import edu.campus.loop.user.CurrentUserContext;
import edu.campus.loop.user.UserDtos.ActiveUser;
import edu.campus.loop.user.UserDtos.UserStatus;
import edu.campus.loop.user.UserFacade;
import java.math.BigDecimal;
import java.util.List;
import java.util.UUID;
import java.util.concurrent.Callable;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicInteger;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.support.StaticListableBeanFactory;
import org.springframework.dao.DataIntegrityViolationException;
import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.support.TransactionSynchronizationManager;
import static edu.campus.loop.trade.TradeDtos.*;
import static org.junit.jupiter.api.Assertions.*;


/** 使用真实 JDBC 与事务；H2 的生成列唯一约束模拟 PostgreSQL 的部分唯一索引。 */
class TradeServiceTest {
    private JdbcTemplate jdbc;
    private TradeService service;
    private final ThreadLocal<Long> actor = ThreadLocal.withInitial(() -> 1L);
    private UserFacade users;
    private final java.util.Set<Long> disabledUsers = new java.util.HashSet<>();
    private final AtomicInteger soldCalls = new AtomicInteger();

    @BeforeEach
    void setUp() {
        var dataSource = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID()
                + ";MODE=PostgreSQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=10000", "sa", "");
        jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("CREATE TABLE products(id BIGINT PRIMARY KEY, seller_id BIGINT, status VARCHAR(16), version BIGINT)");
        jdbc.update("INSERT INTO products VALUES (10, 2, 'ON_SALE', 0)");
        jdbc.execute("""
                CREATE TABLE trades(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                product_id BIGINT NOT NULL, buyer_id BIGINT NOT NULL, seller_id BIGINT NOT NULL,
                message VARCHAR(500), status VARCHAR(16), created_at TIMESTAMP WITH TIME ZONE,
                updated_at TIMESTAMP WITH TIME ZONE,
                pending_product BIGINT GENERATED ALWAYS AS (CASE WHEN status = 'PENDING' THEN product_id ELSE NULL END),
                CONSTRAINT uk_product_active_trade UNIQUE(pending_product), CHECK(buyer_id <> seller_id))
                """);
        jdbc.execute("""
                CREATE TABLE trade_status_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                trade_id BIGINT REFERENCES trades(id), from_status VARCHAR(16), to_status VARCHAR(16),
                operator_id BIGINT, created_at TIMESTAMP WITH TIME ZONE)
                """);
        users = new UserFacade() {
            public ActiveUser getActiveUser(long id) {
                return disabledUsers.contains(id) ? new ActiveUser(id, "disabled", UserStatus.DISABLED) : active(id);
            }
            public boolean existsActiveUser(long id) { return !disabledUsers.contains(id); }
        };
        ProductFacade products = new ProductFacade() {
            public void lockProduct(long id) {
                assertTrue(TransactionSynchronizationManager.isActualTransactionActive());
                jdbc.queryForObject("SELECT id FROM products WHERE id = ? FOR UPDATE", Long.class, id);
            }
            public TradableProduct getTradableProduct(long id) {
                return jdbc.queryForObject("SELECT * FROM products WHERE id = ?", (rs, row) -> {
                    if (!rs.getString("status").equals("ON_SALE")) {
                        throw new BusinessException(HttpStatus.CONFLICT, "PRODUCT_NOT_TRADABLE", "商品不在售");
                    }
                    return new TradableProduct(id, rs.getLong("seller_id"), BigDecimal.TEN, rs.getLong("version"));
                }, id);
            }
            public void markSold(long id, long version) {
                soldCalls.incrementAndGet();
                int changed = jdbc.update("UPDATE products SET status='SOLD', version=version+1 WHERE id=? AND version=? AND status='ON_SALE'", id, version);
                if (changed != 1) throw new BusinessException(HttpStatus.CONFLICT, "PRODUCT_VERSION_CONFLICT", "版本冲突");
            }
        };
        var beans = new StaticListableBeanFactory();
        beans.addBean("context", (CurrentUserContext) () -> active(actor.get()));
        beans.addBean("repository", new TradeRepository(jdbc));
        beans.addBean("transactions", new DataSourceTransactionManager(dataSource));
        service = new TradeService(beans.getBeanProvider(CurrentUserContext.class), users, products,
                beans.getBeanProvider(TradeRepository.class), beans.getBeanProvider(PlatformTransactionManager.class));
    }

    private ActiveUser active(long id) { return new ActiveUser(id, "user" + id, UserStatus.ACTIVE); }
    private TradeView create() { return service.create(new CreateTradeRequest(10L, "希望购买")); }
    private void assertCode(String code, org.junit.jupiter.api.function.Executable action) {
        assertEquals(code, assertThrows(BusinessException.class, action).code());
    }
    private long logs() { return jdbc.queryForObject("SELECT COUNT(*) FROM trade_status_logs", Long.class); }

    @Test void createRecordsBuyerSellerAndInitialAudit() {
        TradeView trade = create();
        assertEquals(1, trade.buyerId());
        assertEquals(2, trade.sellerId());
        assertEquals(TradeStatus.PENDING, trade.status());
        assertEquals(List.of(TradeStatus.PENDING), trade.logs().stream().map(StatusLog::status).toList());
        assertNull(jdbc.queryForObject("SELECT from_status FROM trade_status_logs", String.class));
        assertEquals(1L, jdbc.queryForObject("SELECT operator_id FROM trade_status_logs", Long.class));
    }

    @Test void duplicatePendingTradeIsConflict() {
        create();
        assertCode("ACTIVE_TRADE_EXISTS", this::create);
        assertEquals(1, logs());
    }

    @Test void validatesRequestAndPagination() {
        assertCode("VALIDATION_ERROR", () -> service.create(new CreateTradeRequest(null, null)));
        assertCode("VALIDATION_ERROR", () -> service.create(new CreateTradeRequest(10L, "x".repeat(501))));
        assertCode("VALIDATION_ERROR", () -> service.list(0, 20, null));
        assertCode("VALIDATION_ERROR", () -> service.list(1, 101, null));
    }

    @Test void cannotBuyOwnProductOrInactiveSeller() {
        actor.set(2L);
        assertCode("BUSINESS_RULE_VIOLATION", this::create);
        actor.set(1L);
        disabledUsers.add(2L);
        assertCode("FORBIDDEN", this::create);
        assertEquals(0, logs());
    }

    @Test void authenticationAndActiveUserRequired() {
        actor.remove();
        disabledUsers.add(1L);
        assertCode("FORBIDDEN", this::create);
        actor.set(null);
        // 独立上下文用 null 表达未认证。
        var beans = new StaticListableBeanFactory();
        beans.addBean("context", (CurrentUserContext) () -> null);
        var unauthenticated = new TradeService(beans.getBeanProvider(CurrentUserContext.class), users,
                null, beans.getBeanProvider(TradeRepository.class),
                beans.getBeanProvider(PlatformTransactionManager.class));
        assertCode("UNAUTHORIZED", () -> unauthenticated.list(1, 20, null));
    }

    @Test void queriesOnlyParticipantsAndFiltersStatus() {
        TradeView trade = create();
        assertEquals(1, service.list(1, 20, null).total());
        assertEquals(0, service.list(1, 20, TradeStatus.ACCEPTED).total());
        assertTrue(service.list(Integer.MAX_VALUE, 100, null).items().isEmpty());
        actor.set(2L);
        assertEquals(trade.id(), service.detail(trade.id()).id());
        assertEquals(1, service.list(1, 20, null).total());
        actor.set(3L);
        assertCode("FORBIDDEN", () -> service.detail(trade.id()));
        assertEquals(0, service.list(1, 20, null).total());
        assertCode("RESOURCE_NOT_FOUND", () -> service.detail(999));
    }

    @Test void acceptingIsAtomicAndIdempotent() {
        long id = create().id();
        assertCode("FORBIDDEN", () -> service.accept(id));
        actor.set(2L);
        TradeView result = service.accept(id);
        assertEquals(TradeStatus.ACCEPTED, result.status());
        assertEquals(result, service.accept(id));
        assertEquals(1, soldCalls.get());
        assertEquals(2, logs());
        assertEquals("SOLD", jdbc.queryForObject("SELECT status FROM products", String.class));
        assertEquals(1L, jdbc.queryForObject("SELECT version FROM products", Long.class));
        assertCode("INVALID_TRADE_TRANSITION", () -> service.reject(id));
        actor.set(1L);
        assertCode("FORBIDDEN", () -> service.accept(id));
        assertCode("INVALID_TRADE_TRANSITION", () -> service.cancel(id));
    }

    @Test void rejectAndCancelRespectRolesAndIdempotency() {
        long id = create().id();
        assertCode("FORBIDDEN", () -> service.reject(id));
        actor.set(2L);
        assertCode("FORBIDDEN", () -> service.cancel(id));
        assertEquals(TradeStatus.REJECTED, service.reject(id).status());
        service.reject(id);
        actor.set(1L);
        long next = create().id();
        assertEquals(TradeStatus.CANCELLED, service.cancel(next).status());
        service.cancel(next);
        assertEquals(4, logs());
        assertEquals("ON_SALE", jdbc.queryForObject("SELECT status FROM products", String.class));
    }

    @Test void logFailureRollsBackSoldProductAndTrade() {
        long id = create().id();
        jdbc.execute("ALTER TABLE trade_status_logs ADD CONSTRAINT fail_accept CHECK(to_status <> 'ACCEPTED')");
        actor.set(2L);
        assertThrows(DataIntegrityViolationException.class, () -> service.accept(id));
        assertEquals("ON_SALE", jdbc.queryForObject("SELECT status FROM products", String.class));
        assertEquals(0L, jdbc.queryForObject("SELECT version FROM products", Long.class));
        assertEquals(TradeStatus.PENDING, service.detail(id).status());
        assertEquals(1, logs());
    }

    @Test void initialLogFailureRollsBackNewTrade() {
        jdbc.execute("ALTER TABLE trade_status_logs ADD CONSTRAINT fail_pending CHECK(to_status <> 'PENDING')");
        assertThrows(DataIntegrityViolationException.class, this::create);
        assertEquals(0L, jdbc.queryForObject("SELECT COUNT(*) FROM trades", Long.class));
    }

    @Test void noLongerTradableProductCannotBeAccepted() {
        long id = create().id();
        jdbc.update("UPDATE products SET status='OFF_SHELF'");
        actor.set(2L);
        assertCode("PRODUCT_NOT_TRADABLE", () -> service.accept(id));
        assertEquals(TradeStatus.PENDING, service.detail(id).status());
        assertEquals(1, logs());
    }

    @Test void apiReturnsBusinessErrorCodeAndHttpStatus() throws Exception {
        var mvc = org.springframework.test.web.servlet.setup.MockMvcBuilders
                .standaloneSetup(new TradeController(service))
                .setControllerAdvice(new edu.campus.loop.common.ApiExceptionHandler()).build();
        long id = create().id();
        mvc.perform(org.springframework.test.web.servlet.request.MockMvcRequestBuilders
                .patch("/api/v1/trades/{id}/accept", id))
                .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers.status().isForbidden())
                .andExpect(org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath("$.code").value("FORBIDDEN"));
    }

    @Test void integratedWebApplicationStartsWithoutTradeDatabase() {
        new org.springframework.boot.test.context.runner.WebApplicationContextRunner()
                .withUserConfiguration(edu.campus.loop.CampusLoopApplication.class)
                // 测试类路径含 H2；关闭自动数据源配置以模拟主程序未配置数据库的启动方式。
                .withPropertyValues("spring.autoconfigure.exclude=org.springframework.boot.autoconfigure.jdbc.DataSourceAutoConfiguration")
                .run(context -> {
                    assertNull(context.getStartupFailure());
                    // 用户模块现已接入，启动测试需要真实的 Web 上下文以注入请求代理。
                    assertNotNull(context.getBean(TradeService.class));
                    assertTrue(context.getBeansOfType(TradeRepository.class).isEmpty());
                    assertTrue(org.springframework.aop.support.AopUtils.isCglibProxy(context.getBean("userRepository")));
                    assertTrue(org.springframework.aop.support.AopUtils.isCglibProxy(context.getBean("authTokenRepository")));
                });
    }

    @Test void databasePropertiesEnableSharedPersistenceBeans() {
        new org.springframework.boot.test.context.runner.WebApplicationContextRunner()
                .withUserConfiguration(edu.campus.loop.CampusLoopApplication.class)
                .withPropertyValues("spring.datasource.url=jdbc:h2:mem:configuration;MODE=PostgreSQL",
                        "spring.datasource.username=sa", "spring.datasource.password=")
                .run(context -> {
                    assertNull(context.getStartupFailure());
                    assertNotNull(context.getBean(TradeRepository.class));
                    assertEquals(1, context.getBeansOfType(PlatformTransactionManager.class).size());
                });
    }

    @Test void concurrentApplicationsAllowOnlyOnePendingTrade() throws Exception {
        try (var pool = Executors.newFixedThreadPool(2)) {
            Callable<String> request = () -> {
                actor.set(1L);
                try { create(); return "OK"; }
                catch (BusinessException exception) { return exception.code(); }
                finally { actor.remove(); }
            };
            var results = pool.invokeAll(List.of(request, request));
            var codes = List.of(results.get(0).get(), results.get(1).get());
            assertTrue(codes.contains("OK"));
            assertTrue(codes.contains("ACTIVE_TRADE_EXISTS"));
            assertEquals(1, logs());
        }
    }

    @Test void concurrentAcceptsSellOnce() throws Exception {
        long id = create().id();
        try (var pool = Executors.newFixedThreadPool(2)) {
            Callable<TradeView> accept = () -> {
                actor.set(2L);
                try { return service.accept(id); } finally { actor.remove(); }
            };
            for (var result : pool.invokeAll(List.of(accept, accept))) {
                assertEquals(TradeStatus.ACCEPTED, result.get().status());
            }
            assertEquals(1, soldCalls.get());
            assertEquals(2, logs());
        }
    }
}
