package edu.campus.loop.user;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * 用户模块的 JDBC 事务边界。
 * <p>连接参数来自 {@code spring.datasource.*}，与商品、交易模块指向同一个数据库文件，
 * 因此用户、商品、交易数据持久化在同一处，重启后仍然保留。</p>
 */
@Component
class UserDatabase {
    private final String url;
    private final String username;
    private final String password;
    private volatile boolean initialized;

    UserDatabase(@Value("${spring.datasource.url}") String url,
                 @Value("${spring.datasource.username:sa}") String username,
                 @Value("${spring.datasource.password:}") String password) {
        this.url = url;
        this.username = username;
        this.password = password;
    }

    @FunctionalInterface interface Work<T> { T run(Connection connection) throws SQLException; }

    <T> T read(Work<T> work) {
        initialize();
        try (Connection connection = DriverManager.getConnection(url, username, password)) {
            return work.run(connection);
        } catch (SQLException failure) { throw translate(failure); }
    }

    <T> T transaction(Work<T> work) {
        initialize();
        try (Connection connection = DriverManager.getConnection(url, username, password)) {
            connection.setAutoCommit(false);
            try {
                T result = work.run(connection);
                connection.commit();
                return result;
            } catch (SQLException | RuntimeException failure) {
                connection.rollback();
                throw failure;
            }
        } catch (SQLException failure) { throw translate(failure); }
    }

    /** 唯一键冲突统一翻译为业务错误；SQLState 23505 为 PostgreSQL / H2 的唯一约束违反。 */
    private RuntimeException translate(SQLException failure) {
        if ("23505".equals(failure.getSQLState()))
            return new UserFailure(409, "ACCOUNT_EXISTS", "该账号已注册");
        return new IllegalStateException("User persistence failure", failure);
    }

    /** 独立入口（user-pom.xml）不加载公共建表组件，这里保证用户相关表存在；重复执行无副作用。 */
    private synchronized void initialize() {
        if (initialized) return;
        if (url.startsWith("jdbc:h2:")) {
            try (Connection connection = DriverManager.getConnection(url, username, password);
                 var statement = connection.createStatement()) {
                statement.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      account VARCHAR(64) NOT NULL UNIQUE,
                      password_hash VARCHAR(255) NOT NULL,
                      nickname VARCHAR(64) NOT NULL,
                      avatar_url VARCHAR(512),
                      phone VARCHAR(32),
                      status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE'
                        CHECK(status IN ('ACTIVE','DISABLED')),
                      created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                      updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP)
                    """);
                statement.execute("""
                    CREATE TABLE IF NOT EXISTS auth_tokens (
                      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                      user_id BIGINT NOT NULL REFERENCES users(id),
                      token_hash VARCHAR(128) NOT NULL UNIQUE,
                      expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
                      revoked_at TIMESTAMP WITH TIME ZONE,
                      created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP)
                    """);
                statement.execute("CREATE INDEX IF NOT EXISTS idx_auth_tokens_user_active ON auth_tokens(user_id, expires_at)");
            } catch (SQLException failure) { throw translate(failure); }
        }
        initialized = true;
    }
}
